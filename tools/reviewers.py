"""Rebuild REVIEWERS.md: one row per page with its last review date and open ⚠️ count.

Usage: python3 tools/reviewers.py
Reviewer names that people typed into the last column are kept.
"""
import re, pathlib
repo = pathlib.Path(__file__).resolve().parent.parent; fa = "International" not in repo.name
REV = re.compile(r"(?:\*\*Last reviewed:\*\*|تاریخ آخرین بررسی:\*\*)\s*(\d{4}-\d{2}-\d{2})")
old = {}
if (repo/"REVIEWERS.md").exists():
    for l in (repo/"REVIEWERS.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"\| \[.*?\]\(handbook/(.*?)\) \|.*\| ([^|]*) \|$", l)
        if m: old[m.group(1)] = m.group(2).strip()
rows = []
for p in sorted((repo/"handbook").glob("[0-9][0-9]-*/[0-9][0-9]-*.md")):
    t = p.read_text(encoding="utf-8")
    title = t.split("\n",1)[0].lstrip("# ").strip()
    body = re.sub(r"<!-- disclaimer:start -->.*?<!-- disclaimer:end -->","",t,flags=re.S)
    flags = sum(1 for l in body.splitlines() if "⚠️" in l and "⚠️ =" not in l and "این صفحه ⚠️" not in l and "= نیازمند" not in l and "= needs" not in l)
    m = REV.search(t); rel = p.relative_to(repo/"handbook").as_posix()
    rows.append((rel, title, m.group(1) if m else "—", flags))
if fa:
    head = """# بازبین‌های کتابچه

این صفحه می‌گوید **کدام صفحه را چه کسی بازبینی کرده**. دلیل آن ساده است: «تاریخ آخرین بررسی» باید یعنی یک نفر واقعاً صفحه را با منبع رسمی مقایسه کرده است، نه اینکه پیوندها باز شده‌اند.

## بازبین چه می‌کند؟

1. یک صفحه را برمی‌دارد و در ستون «بازبین» همین جدول (از راه Pull Request) نام یا نام کاربری GitHub خود را می‌نویسد.
2. هر ادعا و عدد صفحه را با منبع رسمی همان‌جا مقایسه می‌کند؛ ⚠️ها را بررسی می‌کند و پیوند خراب را اصلاح می‌کند.
3. «تاریخ آخرین بررسی» صفحه را به تاریخ امروز تغییر می‌دهد و در توضیح Pull Request می‌نویسد چه چیزی را با کدام منبع مقایسه کرده است.

## چه کسی مناسب است؟

- کسی که **خودش اخیراً** همان کار اداری را انجام داده (مثلاً ثبت محل سکونت، بیمه، اجازه اقامت، ویزا).
- برای صفحه‌های مربوط به کنسولگری و ویزا، ترجیحاً کسی که در یک سال گذشته با همان نهاد کار کرده است.
- برای متن فارسی، کسی که نگارش را هم بررسی کند.

هیچ تخصص حقوقی لازم نیست؛ ولی بازبین مشاور حقوقی نیست و باید هر جا مطمئن نیست «از نهاد رسمی بپرسید» بنویسد.

## جدول صفحه‌ها

ستون «⚠️» تعداد موارد باز را نشان می‌دهد. جدول با اسکریپت ساخته شده؛ نام بازبین را دستی اضافه کنید.

| صفحه | آخرین بررسی | ⚠️ | بازبین |
|---|---|---|---|
"""
    foot = "\n[چطور کمک کنم؟](CONTRIBUTING.md) · [اهداف و نقشه راه](ROADMAP.md)\n"
else:
    head = """# Reviewers

This page records **who reviewed which page**. The reason is simple: "Last reviewed" should mean that a person compared the page with the official sources, not that the links opened.

## What does a reviewer do?

1. Takes one page and writes their name or GitHub username in the "Reviewer" column of this table (through a pull request).
2. Compares each claim and figure on the page with the official source, checks the ⚠️ items and fixes broken links.
3. Sets the page's "Last reviewed" date to today and says in the pull request what was compared with which source.

## Who is a good reviewer?

- Someone who **recently went through** the same process themselves (for example Anmeldung, insurance, residence permit or the visa).
- For Section 8 (information by nationality), someone from the nationality or status concerned, ideally with recent experience of the embassy or office.
- For the English text, someone who also checks the wording.

No legal training is needed, but a reviewer is not a legal adviser and should write "ask the official office" wherever they are not sure.

## Pages

The "⚠️" column counts open items. The table is generated by a script; add reviewer names by hand.

| Page | Last reviewed | ⚠️ | Reviewer |
|---|---|---|---|
"""
    foot = "\n[How to help](CONTRIBUTING.md) · [Goals and roadmap](ROADMAP.md)\n"
body = "".join(f"| [{t}](handbook/{rel}) | {d} | {f or '—'} | {old.get(rel, '')} |\n" for rel,t,d,f in rows)
(repo/"REVIEWERS.md").write_text(head+body+foot, encoding="utf-8")
print(repo.name, len(rows))
